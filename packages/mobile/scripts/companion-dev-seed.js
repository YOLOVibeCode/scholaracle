/**
 * How companion.env.local (a developer's own school-portal sign-in, gitignored) becomes
 * src/credentials/companionDevSeed.generated.ts.
 *
 * metro.config.js calls syncCompanionDevSeed() every time the bundler starts: for the development
 * server, and also for `expo export`, `eas update` and store builds. Two rules keep the sign-in out
 * of anything that ships:
 *
 * 1. companion.env.local is read only when the bundler runs as the development server, which is
 *    when NODE_ENV is "development" (`expo start`, `expo run:*`). Every other run does not open the
 *    file and writes the null module. `expo export` forces NODE_ENV to "production", so an OTA
 *    update can never be the run that writes a seed.
 * 2. A seed that is written is only reachable under __DEV__. A production bundle is built with
 *    __DEV__ = false and Metro removes the dead branch, so the values are not in the bundle even
 *    when rule 1 is bypassed (a release build started from a shell that exports
 *    NODE_ENV=development).
 *
 * Both rules are held by src/credentials/companionDevSeedGenerator.test.ts.
 */

const fs = require('fs');
const path = require('path');

const COMPANION_ENV_FILE = 'companion.env.local';
const GENERATED_MODULE = 'src/credentials/companionDevSeed.generated.ts';
const PROVIDERS = ['canvas', 'skyward', 'aeries'];

/**
 * @typedef {object} CompanionDevSeed
 * @property {string} provider
 * @property {string} baseUrl
 * @property {string} username
 * @property {string} password
 * @property {string} studentExternalId
 * @property {string} sourceId
 */

/**
 * Parse KEY=VALUE dotenv lines (no dependency). Skips comments/blank.
 * @param {string} src
 * @returns {Record<string, string>}
 */
function parseDotEnv(src) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const raw of src.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

/**
 * Rule 1: only the development server may read companion.env.local.
 * @param {string | undefined} nodeEnv
 * @returns {boolean}
 */
function isDevelopmentServer(nodeEnv) {
  return nodeEnv === 'development';
}

/**
 * @param {Record<string, string>} parsed
 * @returns {CompanionDevSeed | null} null unless every required field is there
 */
function seedFromCompanionEnv(parsed) {
  const provider = parsed['COMPANION_PORTAL_PROVIDER'];
  const baseUrl = parsed['COMPANION_PORTAL_BASE_URL'];
  const username = parsed['COMPANION_PORTAL_USERNAME'];
  const password = parsed['COMPANION_PORTAL_PASSWORD'];
  const studentExternalId = parsed['COMPANION_STUDENT_EXTERNAL_ID'] || 'dev-student';
  const sourceId = parsed['COMPANION_SOURCE_ID'] || 'dev-source';

  if (!provider || !baseUrl || !username || !password || !PROVIDERS.includes(provider)) {
    return null;
  }
  return { provider, baseUrl, username, password, studentExternalId, sourceId };
}

/**
 * Rule 2: the value of COMPANION_DEV_SEED. A seed is always behind the __DEV__ check.
 * @param {CompanionDevSeed | null} seed
 * @returns {string}
 */
function renderSeedExpression(seed) {
  if (!seed) return 'null';
  return `typeof __DEV__ !== 'undefined' && __DEV__ ? ${JSON.stringify(seed)} : null`;
}

/**
 * @param {CompanionDevSeed | null} seed
 * @returns {string} the text of src/credentials/companionDevSeed.generated.ts
 */
function renderSeedModule(seed) {
  return `/**
 * AUTO-GENERATED by metro.config.js from companion.env.local — do not edit.
 * Gitignored. Never commit. Null unless the development server wrote it, and a production bundle
 * drops the value either way (__DEV__ is false there).
 */
import type { ICompanionDevPortalSeed } from './devCredentialSeed';

export const COMPANION_DEV_SEED: ICompanionDevPortalSeed | null = ${renderSeedExpression(seed)};
`;
}

/**
 * Write the generated module for this bundler run.
 *
 * @param {object} options
 * @param {string} options.projectRoot packages/mobile
 * @param {string | undefined} options.nodeEnv NODE_ENV of the bundler process
 * @param {Record<string, string | undefined>} [options.env] where the file's variables are copied
 *   for the development server (defaults to process.env)
 * @returns {'seeded' | 'none' | 'skipped'} "skipped": the file is there but this run may not read it
 */
function syncCompanionDevSeed({ projectRoot, nodeEnv, env = process.env }) {
  const companionPath = path.join(projectRoot, COMPANION_ENV_FILE);
  const genPath = path.join(projectRoot, GENERATED_MODULE);

  /** @type {CompanionDevSeed | null} */
  let seed = null;
  /** @type {'seeded' | 'none' | 'skipped'} */
  let outcome = 'none';

  if (fs.existsSync(companionPath)) {
    if (isDevelopmentServer(nodeEnv)) {
      const parsed = parseDotEnv(fs.readFileSync(companionPath, 'utf8'));
      Object.assign(env, parsed);
      seed = seedFromCompanionEnv(parsed);
      outcome = seed ? 'seeded' : 'none';
    } else {
      outcome = 'skipped';
    }
  }

  fs.mkdirSync(path.dirname(genPath), { recursive: true });
  fs.writeFileSync(genPath, renderSeedModule(seed));
  return outcome;
}

module.exports = {
  COMPANION_ENV_FILE,
  GENERATED_MODULE,
  isDevelopmentServer,
  parseDotEnv,
  renderSeedExpression,
  renderSeedModule,
  seedFromCompanionEnv,
  syncCompanionDevSeed,
};
