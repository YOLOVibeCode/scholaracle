/**
 * Renders the build-time page-function source table. Run only under Node (the
 * generator script and its freshness test), where Function.prototype.toString
 * returns real source.
 */
export function renderPageFnSources(
  registry: Readonly<Record<string, (...args: never[]) => unknown>>
): string {
  const ids = Object.keys(registry).sort();
  const lines = ids.map((id) => {
    const source = Function.prototype.toString.call(registry[id]);
    if (/\[bytecode\]|\[native code\]/.test(source)) {
      throw new Error(`Page function ${id} has no source (got: ${source.slice(0, 60)})`);
    }
    return `  ${JSON.stringify(id)}: ${JSON.stringify(source)},`;
  });
  return [
    '/* eslint-disable */',
    '// GENERATED by scripts/build-page-fns.ts from src/page-fns/registry.ts. Do not edit.',
    '// Regenerate: pnpm --filter @scholaracle/scraper-core page-fns',
    '',
    '/** Page function id -> JavaScript source, captured at build time (see registry.ts). */',
    'export const PAGE_FN_SOURCES: Readonly<Record<string, string>> = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}
